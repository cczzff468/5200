export type AuthorKey = string; // 'user' | 'anon' | 'char:<contactId>' | 'npc:<id>' | 'official'

/** 匿名账号（小号）作者 key：发帖/评论/点赞/私信归属与主账号（'user'）完全隔离。
 *  AI 认知隔离：resolveAuthor('anon') 只返回匿名身份（网名/handle/头像），
 *  NPC/角色看到的就是一个普通陌生网友，绝不关联机主本人。 */
export const ANON_KEY = 'anon';

export interface ForumAuthor {
  key: AuthorKey;
  name: string;
  handle: string; // 不带 @
  avatar: string | null; // dataURL（user/char）；NPC = 头像库图片（加载失败/未分配时 XAvatar 用纯色系 flat 池兑底）
  /** 彩底首字头像（仅官方账号「助」字徽章还在用；网友已全部改用图片头像） */
  npcAvatar?: { bg: string; ch: string };
  /** 认证蓝 V（大 V NPC / 官方账号） */
  verified?: boolean;
  /** 一句话简介（个人页展示） */
  bio?: string;
  /** 粉丝数（NPC 基础值；user/char 动态算） */
  baseFollowers?: number;
  /** 生成用人设（NPC 发帖/回复的 LLM prompt；char 用联系人 persona） */
  persona?: string;
  /** 惯用发帖语言（动态虚拟用户：zh-Hans/zh-Hant/en/ja/ko；缺省 = 简体中文） */
  lang?: string;
  /** IP 属地（评论区展示：北京/广东/日本…；user/官方无） */
  ip?: string;
}

export interface ForumPost {
  id: string;
  authorKey: AuthorKey;
  content: string;
  /** 版块 id（null = 今日热议广场） */
  community: string | null;
  createdAt: number;
  /** 点过赞的作者 key 列表（含 'user'） */
  likes: AuthorKey[];
  /** 转推数（模拟增长） */
  reposts: number;
  views: number;
  /** 合成点赞基数（AI 帖子按热度分层生成：十几/几十/几百/几千/几万/几十万/几百万；
   *  展示数 = likes.length + likeBoost，用户点赞仍写 likes 数组） */
  likeBoost?: number;
  /** 我是否转推过（X 转推可撤销；true 时绿高亮） */
  reposted?: boolean;
  /** 回复链：回复某帖时同时是一条帖（X 语义：回复即发帖） */
  replyTo: string | null;
  replyToName: string | null;
  /** 精确被回复对象的帖子 id（多轮对话定位用）。
   *  replyTo 是分组锚点（顶层评论/主帖 id，决定显示在哪一层）；
   *  replyToPost 记录实际回复的那条（子回复/主帖），AI 据此接话（无限多轮）。 */
  replyToPost?: string;
  /** 帖子附图（dataURL 或 http URL，最多 4 张；发布界面相册/GIF 上传） */
  media?: string[];
  /** 文字图片源文本（与 media 按下标对齐；文字图片项存渲染前的原文——
   *  点击卡片生成真图时预填提示词（可改）；非文字图项为 ''；
   *  旧数据无此字段时回退用帖子正文预填） */
  mediaText?: string[];
  /** 投票（发布界面发起） */
  poll?: PostPoll;
  /** 位置名（发布界面添加，帖子卡展示 📍） */
  location?: string;
  /** 定时发布：到该时刻才出现在列表（undefined = 立即可见；createdAt 同步取该值） */
  visibleAt?: number;
}

/** 帖子投票：选项文本 + 每项票数 + 我投的选项 index（null = 未投） */
export interface PostPoll {
  options: string[];
  votes: number[];
  voted?: number | null;
}

