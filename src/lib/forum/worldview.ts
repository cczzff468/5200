/** 深拷贝内置世界观（store 初始化时展开成用户可编辑的副本） */
export function cloneBuiltinWorldviews(): WorldviewDef[] {
  return BUILTIN_WORLDVIEWS.map((wv) => ({
    ...wv,
    tags: [...wv.tags],
    seedPool: [...wv.seedPool],
    matrix: wv.matrix.map((n) => ({ ...n })),
  }));
}

/** 重置某个内置世界的矩阵到出厂阵容 */
export function builtinMatrixOf(id: string): MatrixNpc[] | null {
  const wv = BUILTIN_WORLDVIEWS.find((w) => w.id === id);
  if (!wv) return null;
  return wv.matrix.map((n) => ({ ...n }));
}
