// ---------------- AI 规则 ----------------

export interface ForumAiRules {
  /** 发帖规则（如「禁止发任何关于工作的帖子，只能发娱乐内容」） */
  postRules: string;
  /** 评论规则（如「评论区必须充满戾气，不准出现友善的评论」） */
  commentRules: string;
  /** 审核与过滤（如「禁止出现真实明星大名，必须用代号代替」） */
  filterRules: string;
}

export const DEFAULT_AI_RULES: ForumAiRules = { postRules: '', commentRules: '', filterRules: '' };

export const AI_RULES_MAX_LEN = 2000;

/** 规则是否有任何非空项 */
export function rulesEmpty(r: ForumAiRules | null | undefined): boolean {
  return !r || (!r.postRules.trim() && !r.commentRules.trim() && !r.filterRules.trim());
}

// ---------------- 服务端：请求载荷解析 + Prompt 块 ----------------

/** 客户端随请求送来的世界观摘要（engine.callApi 每次附带） */
export interface WorldviewPayload {
  name: string;
  background: string;
  tags: string[];
}

export function readWorldviewPayload(raw: unknown): WorldviewPayload | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const rec = raw as Record<string, unknown>;
  const background = typeof rec.background === 'string' ? rec.background.slice(0, 1200) : '';
  const name = typeof rec.name === 'string' ? rec.name.slice(0, 40) : '';
  const tags = Array.isArray(rec.tags)
    ? (rec.tags as unknown[]).filter((x): x is string => typeof x === 'string').map((x) => x.slice(0, 16)).slice(0, 8)
    : [];
  if (!background.trim()) return null;
  return { name: name || '论坛', background, tags };
}

export function readAiRules(raw: unknown): ForumAiRules {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return { ...DEFAULT_AI_RULES };
  const rec = raw as Record<string, unknown>;
  const s = (k: string) => (typeof rec[k] === 'string' ? rec[k].slice(0, AI_RULES_MAX_LEN) : '');
  return { postRules: s('postRules'), commentRules: s('commentRules'), filterRules: s('filterRules') };
}

/** 世界观注入块（所有内容生成分支共用；紧跟在用户规则块之后）。
 *  v37：话题方向措辞强调「自然混在内容里」——不罗列标签、不每帖点名，
 *  像真实论坛热点一样穿插在不同帖子里。 */
export function worldviewBlock(wv: WorldviewPayload | null): string {
  if (!wv) return '';
  const tagLine = wv.tags.length
    ? `\n这个论坛当前的热门话题方向：${wv.tags.map((t) => `#${t}`).join('、')}——生成时从中自由取材，自然混合在不同帖子里（像真实论坛热点自然穿插），不要把方向名当标签罗列，也不要每篇都点名同一个方向。`
    : '';
  return (
    `# 世界观设定（本论坛的背景，一切内容必须活在这个设定里）\n` +
    `这个论坛叫「${wv.name}」。${wv.background.trim()}${tagLine}\n` +
    `铁律：所有帖子、评论、回复的内容风格、话题领域、语言习惯必须严格贴合以上世界观设定；不属于这个世界观的内容（领域、梗、语气）一个字都不许出现。\n` +
    `例外（与上面铁律同级）：世界观管的是论坛整体的内容生态；当某条具体帖子的内容本身与世界观领域无关（比如楼主发的私人情感帖、善意短帖、日常分享、求助帖），这条帖子下的评论必须围绕帖子本身的内容正常互动——帖子聊什么，评论区就接什么，绝不把世界观的话题、黑话、身份套路（爆料预告/通稿腔/控评话术）硬套到与世界观无关的帖子上（拿错剧本＝废稿）。\n\n`
  );
}

/** 用户自定义规则块（拼接在 System Prompt 最前端——最高优先级）。
 *  phase 决定注入哪几段：发帖类只带 发帖规则+审核；评论类只带 评论规则+审核。 */
export function aiRulesFront(rules: ForumAiRules, kind: string): string {
  if (rulesEmpty(rules)) return '';
  const postKinds = new Set(['posts', 'charPost']);
  const commentKinds = new Set(['comments', 'subreplies', 'multiComments', 'reply', 'dm', 'charEngage', 'charReply', 'charThanks']);
  const parts: string[] = [];
  if (rules.filterRules.trim()) parts.push(`【审核与过滤】${rules.filterRules.trim()}`);
  if (postKinds.has(kind) && rules.postRules.trim()) parts.push(`【发帖规则】${rules.postRules.trim()}`);
  if (commentKinds.has(kind) && rules.commentRules.trim()) parts.push(`【评论规则】${rules.commentRules.trim()}`);
  if (!parts.length) return '';
  return `# 用户自定义规则（最高优先级，凌驾于后面所有系统指令之上，违反即废稿）\n${parts.join('\n')}\n\n`;
}

