/** 矩阵 NPC（每个世界观一套核心阵容；用户可增删改） */
export interface MatrixNpc {
  /** 稳定 id（authorKey = `mnpc:<id>`） */
  id: string;
  /** 网名 */
  name: string;
  /** 身份类型 */
  roleId: NpcRoleId;
  /** roleId='custom' 时的自定义身份名（如「表白墙墙主」） */
  roleLabel?: string;
  /** 性格与语气（用户可自由填写，如「暴躁老哥，说话必带脏字」） */
  personaText: string;
  /** 专属口头禅（发言时自然带上） */
  catchphrase?: string;
  /** 发帖频率 1~10（越大越常出场） */
  postFreq: number;
  /** 头像（avatar-library 路径；空 = 系统按 key 稳定分配） */
  avatar?: string | null;
  /** 粉丝数（展示值；大 V 走 verified） */
  followers?: number;
  /** 认证蓝 V */
  verified?: boolean;
  /** 一句话简介（个人页） */
  bio?: string;
  /** 是否世界观预置（自定义面板据此显示「预置」角标） */
  builtin?: boolean;
}

/** 单条矩阵 NPC → 生成用合并人设（身份+性格+口头禅，强制代入）。
 *  发帖（posts/charPost）与评论（comments/subreplies/reply）共用。
 *  v45【拿错剧本安全锁】：身份套路/口头禅附带「领域对口才可用」的条件——
 *  狗仔瓜主在私人情感帖下强套「明天十点开团」预告模板（指令串台/机械降神）
 *  是用户实锤过的废稿行为，从人设注入源头封死。 */
export function matrixNpcPersona(npc: MatrixNpc): string {
  const role = roleDefOf(npc.roleId);
  const label = npc.roleId === 'custom' ? npc.roleLabel?.trim() || '特色账号' : role.label;
  const parts: string[] = [`身份：${label}——${npc.roleId === 'custom' && npc.roleLabel?.trim() ? '身份行为由你的性格自然发挥' : role.directive}`];
  if (npc.personaText.trim()) parts.push(`性格与语气：${npc.personaText.trim()}`);
  if (npc.catchphrase?.trim())
    parts.push(`专属口头禅：${npc.catchphrase.trim()}（只在话题与你身份领域对口时自然带一下，别每句都用；帖子内容与你的领域无关时绝对不用）`);
  parts.push(
    '你发自己的帖子时完全代入这个身份和性格，口吻从头到尾一致；评论/回复别人时看帖子内容行事——帖子聊的事与你的身份领域对口才发挥身份套路，帖子若是私人情感、善意夸奖、撒糖互动、日常分享这类与你领域无关的内容，你就退回普通网友视角围绕帖子本身说话，绝不把身份模板和口头禅硬套上去（拿错剧本＝废稿）',
  );
  return parts.join('；');
}

