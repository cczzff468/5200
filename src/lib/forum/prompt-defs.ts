/** 提示词 key（与 /api/forum/generate 的 kind 对应；charThanks 为 charReply 的被赞分支） */
export type PromptKey =
  | 'posts'
  | 'comments'
  | 'subreplies'
  | 'multiComments'
  | 'reply'
  | 'dm'
  | 'charPost'
  | 'charEngage'
  | 'followAsk'
  | 'charReply'
  | 'charThanks'
  | 'ownerReply'
  | 'names';

/** 单条提示词定义 */
export interface PromptDef {
  key: PromptKey;
  /** 展示名（抽屉提示词面板用） */
  label: string;
  /** 一句话说明这条提示词管什么 */
  desc: string;
  /** 可用占位符（面板展示；模板里没写就保持字面） */
  tokens: { token: string; desc: string }[];
  /** 默认模板（route.ts 原 system prompt 逐字搬运） */
  default: string;
}

/** 用户覆盖长度上限（防误粘贴超大文本打爆请求体） */
export const PROMPT_OVERRIDE_MAX_LEN = 30_000;

/** 占位符填充：`{{word}}` → 真实值；未提供值的占位符保持原样 */
export function fillPromptTemplate(tpl: string, vals: Record<string, string | number>): string {
  return tpl.replace(/\{\{(\w+)\}\}/g, (m, k: string) =>
    Object.prototype.hasOwnProperty.call(vals, k) ? String(vals[k]) : m,
  );
}

/** 从请求体读取合法的提示词覆盖（未知 key 忽略；空串视为未覆盖走默认） */
export function readPromptOverrides(raw: unknown): Partial<Record<PromptKey, string>> {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return {};
  const rec = raw as Record<string, unknown>;
  const known = new Set<string>(FORUM_PROMPT_DEFS.map((d) => d.key));
  const out: Partial<Record<PromptKey, string>> = {};
  for (const [k, v] of Object.entries(rec)) {
    if (!known.has(k)) continue;
    if (typeof v !== 'string' || !v.trim()) continue;
    out[k as PromptKey] = v.slice(0, PROMPT_OVERRIDE_MAX_LEN);
  }
  return out;
}

