function buildDeck(): TarotCardDef[] {
  const out: TarotCardDef[] = [];
  for (const [name, nameEn, symbol, numeral, upright, reversed, upKeys, revKeys] of MAJOR) {
    out.push({
      id: `major-${String(out.length).padStart(2, '0')}`,
      name, nameEn, symbol, numeral,
      arcana: 'major',
      upright, reversed, upKeys, revKeys,
    });
  }
  for (const { suit, ranks } of MINOR) {
    const suitEn = TAROT_SUIT_META[suit].nameEn;
    for (const [numeral, upright, reversed, upKeys, revKeys] of ranks) {
      const enRank = numeral === 'A' ? 'Ace' : numeral === '侍从' ? 'Page' : numeral === '骑士' ? 'Knight' : numeral === '王后' ? 'Queen' : numeral === '国王' ? 'King' : numeral;
      out.push({
        id: `${suit}-${numeral}`,
        name: `${TAROT_SUIT_META[suit].name}${numeral}`,
        nameEn: `${enRank} of ${suitEn}`,
        numeral,
        symbol: TAROT_SUIT_META[suit].symbol,
        arcana: 'minor',
        suit,
        upright, reversed, upKeys, revKeys,
      });
    }
  }
  return out;
}

export const TAROT_FULL_DECK: TarotCardDef[] = buildDeck();

export function tarotCardById(id: string): TarotCardDef | undefined {
  return TAROT_FULL_DECK.find((c) => c.id === id);
}

/** 洗牌后随机抽 n 张不重复的牌，各自随机正/逆位 */
export function tarotDraw(n: number): { def: TarotCardDef; reversed: boolean }[] {
  const pool = [...TAROT_FULL_DECK];
  const out: { def: TarotCardDef; reversed: boolean }[] = [];
  for (let i = 0; i < n && pool.length > 0; i++) {
    const k = Math.floor(Math.random() * pool.length);
    out.push({ def: pool[k], reversed: Math.random() < 0.38 });
    pool.splice(k, 1);
  }
  return out;
}

